"""
11-check AST SQL validator using sqlglot.
All checks must pass before the query reaches the database.
"""

from collections.abc import Iterable
from typing import cast

import sqlglot
import sqlglot.expressions as exp

from app.core.friendly_errors import sql_parse_error
from app.config import settings
from app.sql_safety.rules import SQLRuleError, run_raw_checks
from app.sql_safety.sanitizer import inject_limit
from app.utils.logger import logger


class SQLValidationError(Exception):
    """Raised when any of the 11 SQL safety checks fail."""

    def __init__(self, check: int, message: str):
        self.check = check
        self.message = message
        super().__init__(f"[Check {check}] {message}")


# Dialects whose syntax supports a trailing "LIMIT n"
_LIMIT_DIALECTS = {"sqlite", "postgres", "mysql", "duckdb", "bigquery", "snowflake"}

# Top-level statement types that are read-only queries
_SET_OPERATION = getattr(exp, "SetOperation", None) or exp.Union
_ALLOWED_ROOTS = (exp.Select, _SET_OPERATION)

_SYSTEM_SCHEMAS = {
    "pg_catalog",
    "information_schema",
    "sqlite_master",
    "sqlite_schema",
    "sqlite_sequence",
    "sqlite_temp_master",
    "mysql",
    "performance_schema",
    "sys",
}


def default_target_dialect() -> str:
    """sqlglot dialect name for the default TARGET_DB_URL."""
    from app.services.sql_dialect import dialect_from_url

    return dialect_from_url(settings.target_db_url)


def _limit_value(stmt: exp.Expr) -> int | None:
    """Return the integer top-level LIMIT/TOP/FETCH of *stmt*, or None if absent / not a literal."""
    node = stmt.args.get("limit")
    if node is None:
        return None
    value = node.args.get("expression") or node.args.get("count") or node.this
    if isinstance(value, exp.Literal) and not value.is_string:
        try:
            return int(value.this)
        except (TypeError, ValueError):
            return None
    return None


def _enforce_limit(original_sql: str, stmt: exp.Expr, dialect: str, cap: int) -> str:
    """
    Make sure the top-level query returns at most *cap* rows.

    For LIMIT-dialects the user's SQL text is kept as-is whenever possible
    (we only append "LIMIT n"). For SQL Server / Oracle the statement is
    regenerated by sqlglot so TOP / FETCH FIRST syntax is correct.
    """
    has_limit = stmt.args.get("limit") is not None
    current = _limit_value(stmt)

    if has_limit and current is not None and current <= cap:
        return original_sql  # already within cap

    if not has_limit and dialect in _LIMIT_DIALECTS:
        return f"{original_sql.rstrip()} LIMIT {cap}"

    # Needs an AST rewrite (limit too large / non-literal, or dialect without LIMIT)
    try:
        return cast(exp.Query, stmt).limit(cap).sql(dialect=dialect)
    except Exception as exc:  # pragma: no cover - defensive
        logger.warning(f"[VALIDATOR] AST limit rewrite failed ({exc}); falling back to text LIMIT")
        return inject_limit(original_sql, cap)


def validate_sql(
    raw_sql: str,
    dialect: str | None = None,
    allowed_tables: Iterable[str] | None = None,
    max_rows: int | None = None,
) -> str:
    """
    Run all 11 safety checks. Returns the safe SQL string (with a row cap),
    or raises SQLValidationError with the check number and message.

    Args:
        raw_sql:        SQL from the user or the LLM.
        dialect:        sqlglot dialect ("postgres", "mysql", "sqlite", "tsql", "oracle").
                        Defaults to the dialect of TARGET_DB_URL.
        allowed_tables: table names the query may reference. Defaults to the
                        tables of the default target DB. Pass the data source's
                        own tables when querying a dynamic data source.
        max_rows:       row cap (defaults to DB_MAX_ROWS).
    """
    if dialect is None:
        dialect = default_target_dialect()
    cap = max_rows or settings.db_max_rows

    sql = (raw_sql or "").strip()
    # A single trailing semicolon is harmless — drop it before the checks
    while sql.endswith(";"):
        sql = sql[:-1].rstrip()
    if not sql:
        raise SQLValidationError(check=5, message="Empty SQL")

    # ── Checks 1–4: Raw string pre-checks ─────────────────────────────────────
    try:
        run_raw_checks(sql)
    except SQLRuleError as exc:
        raise SQLValidationError(check=1, message=str(exc)) from exc

    # ── Check 5: Must parse cleanly ───────────────────────────────────────────
    try:
        statements = sqlglot.parse(sql, dialect=dialect)
    except (sqlglot.errors.ParseError, sqlglot.errors.TokenError) as exc:
        raise SQLValidationError(check=5, message=sql_parse_error(exc)) from exc
    statements = [s for s in statements if s is not None]
    if not statements:
        raise SQLValidationError(check=5, message="Empty SQL after parsing")

    # ── Check 6: Single statement only ────────────────────────────────────────
    if len(statements) > 1:
        raise SQLValidationError(check=6, message="Only a single SQL statement is allowed")
    stmt = statements[0]

    # ── Check 7: Statement type must be SELECT (incl. WITH / UNION) ───────────
    if not isinstance(stmt, _ALLOWED_ROOTS):
        raise SQLValidationError(
            check=7,
            message=f"Only SELECT statements are allowed, got: {type(stmt).__name__}",
        )

    # ── Check 8: No DDL or DML nodes anywhere in the AST ─────────────────────
    _alter_node = getattr(exp, "AlterTable", None) or getattr(exp, "Alter")
    forbidden = tuple(
        t
        for t in (
            exp.Insert,
            exp.Update,
            exp.Delete,
            exp.Drop,
            exp.Create,
            _alter_node,
            exp.Command,
            exp.Anonymous,
            getattr(exp, "Merge", None),
            getattr(exp, "Into", None),
        )
        if t is not None
    )
    for node in stmt.walk():
        # sqlglot < 26 yields (node, parent, key) tuples from walk()
        if isinstance(node, tuple):
            node = node[0]
        if isinstance(node, forbidden):
            raise SQLValidationError(
                check=8,
                message=f"Operation not allowed: {type(node).__name__}. Only read-only SELECT queries are permitted.",
            )

    # CTE names (WITH x AS ...) are not real tables — exclude them from table checks
    cte_names = {str(cte.alias_or_name).lower() for cte in stmt.find_all(exp.CTE)}

    # ── Check 9: No system tables ─────────────────────────────────────────────
    for table in stmt.find_all(exp.Table):
        schema_name = str(table.args.get("db") or table.args.get("catalog") or "").lower()
        table_name = str(table.name or "").lower()
        if schema_name in _SYSTEM_SCHEMAS:
            raise SQLValidationError(
                check=9, message=f"System schema access blocked: {schema_name}"
            )
        if table_name in _SYSTEM_SCHEMAS:
            raise SQLValidationError(check=9, message=f"System table access blocked: {table_name}")

    # ── Check 10: Every referenced table must be whitelisted ─────────────────
    if allowed_tables is None:
        from app.db.schema_registry import get_allowed_tables

        allowed: set[str] = get_allowed_tables()
    else:
        allowed = {str(t).lower() for t in allowed_tables}
    for table in stmt.find_all(exp.Table):
        table_name = str(table.name or "").lower()
        if not table_name or table_name in cte_names:
            continue
        if table_name not in allowed:
            raise SQLValidationError(
                check=10,
                message=f"Table not in whitelist: '{table_name}'. Allowed: {sorted(allowed)}",
            )

    # ── Check 11: Enforce a row cap ───────────────────────────────────────────
    safe_sql = _enforce_limit(sql, stmt, dialect, cap)

    logger.debug(f"[VALIDATOR] SQL passed all 11 checks: {safe_sql[:120]}...")
    return safe_sql
